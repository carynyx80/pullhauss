/**
 * Helius Solana Privacy Rings integration (@heliuslabs/spr, alpha).
 *
 * pullhaus doesn't run its own shielded pool. Balances, private transfers,
 * proofs and on-chain verification all come from the Privacy Rings default
 * ring (program ring1GaLCuJnkUMVkX2JeZLTTX17wKsV4fZmPVzXANW). This module:
 *   1. connects a browser wallet (Wallet Standard: Phantom, Solflare, Backpack…)
 *   2. derives the user's shielded keys from one wallet signature
 *   3. registers the shielded address in the Rings user registry (once)
 *   4. builds deposit / transfer / multi-transfer / withdrawal transactions,
 *      has the wallet sign them, sends them, and syncs the encrypted balance.
 *
 * Proofs are generated by Helius' remote prover; decryption happens locally.
 */
import {
  buildDepositTransaction,
  buildMultiTransferTransaction,
  buildRegistrationTransaction,
  buildTransferTransaction,
  buildWithdrawalTransaction,
  createSprClient,
  formatAmount,
  getPrivateTokenBalances,
  getPrivateTransactions,
  LocalKeys,
  parseAmount,
  SOL_MINT,
  syncWallet,
  Wallet as ShieldedWallet,
} from '@heliuslabs/spr'
import { SignedTeePolicy } from '@heliuslabs/spr/client'
import { ed25519DerivationMessage } from '@heliuslabs/spr/keypair'
import { isWalletRegistered } from '@heliuslabs/spr/wallet'
import { getTransferSolInstruction } from '@solana-program/system'
import {
  findAssociatedTokenPda,
  getCreateAssociatedTokenIdempotentInstructionAsync,
  getTransferCheckedInstruction,
  TOKEN_PROGRAM_ADDRESS,
} from '@solana-program/token'
import {
  address,
  createNoopSigner,
  getBase64EncodedWireTransaction,
  getTransactionDecoder,
  getTransactionEncoder,
  type Address,
  type Instruction,
  type Transaction,
} from '@solana/kit'
import { getWallets } from '@wallet-standard/app'
import type { Wallet as StdWallet, WalletAccount } from '@wallet-standard/base'

type SprClient = Awaited<ReturnType<typeof createSprClient>>

import { CLUSTER, FEE_BPS, TREASURY } from './config'

const API_KEY = import.meta.env.VITE_HELIUS_API_KEY as string | undefined
const CHAIN = `solana:${CLUSTER}` as const

/** Assets pullhaus exposes in live mode, per cluster. */
export const LIVE_ASSETS: Record<string, { mint: Address; decimals: number }> = {
  SOL: { mint: SOL_MINT, decimals: 9 },
  USDC: {
    mint: address(CLUSTER === 'mainnet' ? 'EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v' : '4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU'),
    decimals: 6,
  },
}
const symbolFor = (mint: string) => Object.entries(LIVE_ASSETS).find(([, a]) => a.mint === mint)?.[0] ?? mint.slice(0, 4) + '…'

export type LiveBalance = { asset: string; amount: number; utxos: number }
export type LiveTx = { id: string; detail: string }

const TREASURY_ADDR = address(TREASURY)
/** pullhaus app fee for an amount in base units (rounded down). */
export const feeFor = (amount: bigint) => (amount * FEE_BPS) / 10_000n

export class RingsSession {
  private constructor(
    readonly client: SprClient,
    readonly wallet: StdWallet,
    readonly account: WalletAccount,
    readonly owner: Address,
    readonly keys: LocalKeys,
    readonly shielded: ShieldedWallet,
    /** Private fee payments need the treasury registered on Privacy Rings. */
    readonly treasuryRegistered: boolean,
  ) {}

  /** True when private transfers carry the app fee. */
  get feesActive() {
    return this.treasuryRegistered && this.owner !== TREASURY_ADDR
  }

  /** Lists installed wallets that can sign messages and transactions. */
  static wallets(): StdWallet[] {
    return getWallets().get().filter((w) => 'solana:signMessage' in w.features && 'solana:signTransaction' in w.features)
  }

  static async connect(wallet: StdWallet, onStatus: (s: string) => void = () => {}): Promise<RingsSession> {
    if (!API_KEY) throw new Error('Set VITE_HELIUS_API_KEY in web/.env.local to use Privacy Rings.')
    onStatus('Connecting wallet')
    const connectFeature = wallet.features['standard:connect'] as { connect(): Promise<{ accounts: readonly WalletAccount[] }> }
    const { accounts } = await connectFeature.connect()
    const account = accounts[0]
    if (!account) throw new Error('Wallet returned no account.')
    const owner = address(account.address)

    onStatus('Starting Privacy Rings client')
    // proverTee: the SDK only sends proof inputs to a prover enclave that attests to
    // Helius' signed policy for this network (AWS Nitro). Required for every remote prover.
    const client = await createSprClient({
      solanaRpcUrl: `https://${CLUSTER}.helius-rpc.com/?api-key=${API_KEY}`,
      proverTee: SignedTeePolicy.forNetwork(CLUSTER),
    })

    onStatus('Sign once to unlock your private balance')
    const message = ed25519DerivationMessage(account.publicKey as Uint8Array as never)
    const signFeature = wallet.features['solana:signMessage'] as {
      signMessage(...i: { account: WalletAccount; message: Uint8Array }[]): Promise<readonly { signature: Uint8Array }[]>
    }
    const [{ signature }] = await signFeature.signMessage({ account, message })
    const keys = LocalKeys.fromDerivationSeed({ solanaPublicKey: owner, derivationSeed: signature }, client.proofService)
    const shielded = new ShieldedWallet({ identity: keys.address() })
    const treasuryRegistered = await isWalletRegistered({ rpc: client, owner: TREASURY_ADDR }).catch(() => false)
    const session = new RingsSession(client, wallet, account, owner, keys, shielded, treasuryRegistered)

    onStatus('Checking registration')
    if (!(await isWalletRegistered({ rpc: client, owner }))) {
      onStatus('Approve one-time registration of your shielded address')
      const tx = await buildRegistrationTransaction({ client, owner, address: keys.address() })
      if (tx) await session.send(tx, false)
    }
    onStatus('Syncing private balance')
    await session.sync()
    return session
  }

  /** Wallet signs, we submit, then wait for the indexer to see it. */
  async send(tx: Transaction, privateTx: boolean): Promise<string> {
    const sign = this.wallet.features['solana:signTransaction'] as {
      signTransaction(...i: { account: WalletAccount; transaction: Uint8Array; chain?: string }[]): Promise<readonly { signedTransaction: Uint8Array }[]>
    }
    // kit types this as ReadonlyUint8Array; wallets want a plain copy
    const bytes = new Uint8Array(getTransactionEncoder().encode(tx) as unknown as Uint8Array)
    const [{ signedTransaction }] = await sign.signTransaction({ account: this.account, transaction: bytes, chain: CHAIN })
    const signed = getTransactionDecoder().decode(signedTransaction)
    const sig = await this.client.solanaRpc.sendTransaction(getBase64EncodedWireTransaction(signed), { encoding: 'base64' }).send()
    if (privateTx) await this.client.confirmPrivateTransaction(sig)
    else await this.client.confirmTransaction(sig)
    return sig
  }

  async sync() {
    await syncWallet({ wallet: this.shielded, keys: this.keys, client: this.client })
  }

  balances(): LiveBalance[] {
    return getPrivateTokenBalances(this.shielded).map((b) => {
      const sym = symbolFor(b.mint)
      const dec = LIVE_ASSETS[sym]?.decimals ?? 0
      return { asset: sym, amount: Number(formatAmount(b.amount, dec)), utxos: b.utxos.length }
    })
  }

  history(): LiveTx[] {
    return getPrivateTransactions(this.shielded).map((t, i) => ({ id: String(i), detail: JSON.stringify(t, (_k, v) => (typeof v === 'bigint' ? v.toString() : v)).slice(0, 140) }))
  }

  private asset(sym: string) {
    const a = LIVE_ASSETS[sym]
    if (!a) throw new Error(`${sym} isn't enabled on Privacy Rings in pullhaus yet. Use SOL or USDC.`)
    return a
  }

  private base() {
    return { client: this.client, wallet: this.shielded, keys: this.keys, feePayer: this.owner }
  }

  /**
   * Public balance → private balance. `recipient` defaults to yourself; any registered Solana
   * address works (payment links). With `chargeFee`, the payer also sends the 0.25% app fee to
   * the treasury in the same transaction. Deposits are public anyway, so this leaks nothing new.
   */
  async deposit(sym: string, amount: string, recipient?: string, chargeFee = false): Promise<string> {
    const a = this.asset(sym)
    const value = parseAmount(amount, a.decimals)
    const fee = chargeFee && this.owner !== TREASURY_ADDR ? feeFor(value) : 0n
    const tx = await buildDepositTransaction({
      client: this.client, feePayer: this.owner, asset: a.mint, amount: value,
      recipient: recipient ? address(recipient) : this.keys.address(),
      setupInstructions: fee > 0n ? await this.feeInstructions(sym, fee) : undefined,
    })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /**
   * Private → private. Amount and asset are hidden; addresses are visible on the default ring.
   * The recipient gets the full amount; the 0.25% app fee is a second private output to the treasury.
   */
  async transfer(sym: string, amount: string, to: string): Promise<string> {
    const a = this.asset(sym)
    const value = parseAmount(amount, a.decimals)
    const fee = this.feesActive ? feeFor(value) : 0n
    const tx = fee > 0n
      ? await buildMultiTransferTransaction({
          ...this.base(), asset: a.mint,
          payments: [{ recipient: address(to), amount: value }, { recipient: TREASURY_ADDR, amount: fee }],
        })
      : await buildTransferTransaction({ ...this.base(), recipient: address(to), asset: a.mint, amount: value })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Most payroll recipients per transaction (Rings allows 15 outputs; one is the fee). */
  get maxRecipients() {
    return this.feesActive ? 14 : 15
  }

  /** One private transaction paying many recipients (payroll), plus the app fee on the total. */
  async multiTransfer(sym: string, payments: { to: string; amount: string }[]): Promise<string> {
    const a = this.asset(sym)
    if (payments.length > this.maxRecipients) throw new Error(`Up to ${this.maxRecipients} recipients per transaction.`)
    const outs = payments.map((p) => ({ recipient: address(p.to), amount: parseAmount(p.amount, a.decimals) }))
    const fee = this.feesActive ? feeFor(outs.reduce((s, o) => s + o.amount, 0n)) : 0n
    const tx = await buildMultiTransferTransaction({
      ...this.base(), asset: a.mint,
      payments: fee > 0n ? [...outs, { recipient: TREASURY_ADDR, amount: fee }] : outs,
    })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Private balance → public Solana address. */
  async withdraw(sym: string, amount: string, to: string): Promise<string> {
    const a = this.asset(sym)
    const tx = await buildWithdrawalTransaction({ ...this.base(), recipient: address(to), asset: a.mint, amount: parseAmount(amount, a.decimals) })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Public fee transfer to the treasury (SOL, or SPL to the treasury's token account). */
  private async feeInstructions(sym: string, fee: bigint): Promise<Instruction[]> {
    const a = this.asset(sym)
    const payer = createNoopSigner(this.owner)
    if (a.mint === SOL_MINT) return [getTransferSolInstruction({ source: payer, destination: TREASURY_ADDR, amount: fee })]
    const [source] = await findAssociatedTokenPda({ owner: this.owner, mint: a.mint, tokenProgram: TOKEN_PROGRAM_ADDRESS })
    const [destination] = await findAssociatedTokenPda({ owner: TREASURY_ADDR, mint: a.mint, tokenProgram: TOKEN_PROGRAM_ADDRESS })
    return [
      await getCreateAssociatedTokenIdempotentInstructionAsync({ payer, owner: TREASURY_ADDR, mint: a.mint }),
      getTransferCheckedInstruction({ source, mint: a.mint, destination, authority: payer, amount: fee, decimals: a.decimals }),
    ]
  }

  async disconnect() {
    const f = this.wallet.features['standard:disconnect'] as { disconnect(): Promise<void> } | undefined
    await f?.disconnect().catch(() => {})
  }
}
