/** Assets pullhaus exposes in live mode, per cluster. */
export const LIVE_ASSETS: Record<string, { mint: Address; decimals: number }> = {
  SOL: { mint: SOL_MINT, decimals: 9 },
  USDC: {
    mint: address(CLUSTER === 'mainnet' ? 'EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v' : '4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU'),
    decimals: 6,
  },
}
const symbolFor = (mint: string) => Object.entries(LIVE_ASSETS).find(([, a]) => a.mint === mint)?.[0] ?? mint.slice(0, 4) + '…'

/**
 * Sign-in message. Plain UTF-8 so every wallet signs it: Phantom and others refuse
 * the binary "solana offchain" envelope the SDK's own derivation uses.
 */
export const signInMessage = (owner: string) =>
  `Sign in to pullhaus\n\nThis unlocks your private balance on Helius Privacy Rings. It is free and does not send a transaction.\n\nOnly sign this on www.pullhaus.xyz.\n\nWallet: ${owner}\nVersion: 1`

const enc = new TextEncoder()
async function hkdf(ikm: Uint8Array, info: string, bits: number) {
  const key = await crypto.subtle.importKey('raw', ikm as BufferSource, 'HKDF', false, ['deriveBits'])
  return new Uint8Array(await crypto.subtle.deriveBits({ name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(), info: enc.encode(info) }, key, bits))
}

/**
 * Mirrors the SDK's roleExpansion (HKDF-SHA256, same labels and sizes), seeded by the
 * wallet's 64-byte signature over the plain-text message. The signing key stays the
 * wallet's own key, as the Privacy Rings registry requires. Ed25519 signatures are
 * deterministic, so the same wallet always gets the same private address.
 */
async function keysFromSignature(walletPub: Uint8Array, sig: Uint8Array, proofs: SprClient['proofService']) {
  const nf = await hkdf(sig, 'TSPP/nf_key/ed25519/v1', 248)
  const vk = await hkdf(sig, 'TSPP/view_key/ed25519/x25519/v1', 256)
  vk[0] &= 248
  vk[31] = (vk[31] & 127) | 64
  const viewing = ViewingKey.fromBytes(vk as never)
  const nullifier = NullifierKey.fromSecret(nf as never)
  nf.fill(0)
  vk.fill(0)
  const address = ShieldedAddress.fromPublicKeys(ShieldedPublicKey.fromEd25519(walletPub as never), nullifier.publicKey(), viewing.publicKey())
  return LocalKeys.fromKeys({ address, viewingKeys: [viewing], nullifierKey: nullifier }, proofs)
}

async function verifyEd25519(pub: Uint8Array, msg: Uint8Array, sig: Uint8Array) {
  try {
    const key = await crypto.subtle.importKey('raw', pub as BufferSource, { name: 'Ed25519' }, false, ['verify'])
    return await crypto.subtle.verify('Ed25519', key, sig as BufferSource, msg as BufferSource)
  } catch {
    return true // very old browsers without WebCrypto Ed25519: the registry check below still guards keys
  }
}

const REGISTRY_RECORD_BYTES = 100n
/** Network fee plus priority-fee headroom for one transaction, in lamports. */
const TX_FEE_MARGIN = 50_000n
const lamportsToSol = (l: bigint) => (Number(l) / 1e9).toLocaleString('en-US', { maximumFractionDigits: 6 })
async function rentFor(client: SprClient, bytes: bigint) {
  return client.solanaRpc.getMinimumBalanceForRentExemption(bytes).send()
}
/**
 * Solana rejects a transaction that leaves the fee payer below its own rent-exempt
 * minimum. Check up front and say exactly how much SOL is needed, instead of
 * surfacing a raw INSUFFICIENT_FUNDS_FOR_RENT error after the wallet prompt.
 */
async function ensureSol(client: SprClient, owner: Address, what: string, spend: bigint) {
  const [{ value: bal }, keep] = await Promise.all([client.solanaRpc.getBalance(owner).send(), rentFor(client, 0n)])
  const need = spend + keep
  if (bal < need) {
    throw new Error(
      `Your wallet needs at least ${lamportsToSol(need)} SOL for ${what} (it has ${lamportsToSol(bal)} SOL). ` +
      `Add about ${lamportsToSol(need - bal + 1_000_000n)} SOL to this wallet and try again.`,
    )
  }
}

const sameBytes = (a: Uint8Array, b: Uint8Array) => a.length === b.length && a.every((v, i) => v === b[i])

/* ---------------- Jupiter swap (public leg between withdraw and deposit) ---------------- */
const JUP = 'https://lite-api.jup.ag/swap/v1'
export const SWAP_SLIPPAGE_BPS = 50
/** The SDK's native-SOL id is the System Program; Jupiter routes native SOL as wrapped SOL. */
const WSOL = 'So11111111111111111111111111111111111111112'
const jupMint = (m: string) => (m === SOL_MINT ? WSOL : m)
export type SwapQuote = {
  inAmount: string; outAmount: string; otherAmountThreshold: string; priceImpactPct: string
  routePlan?: { swapInfo?: { label?: string } }[]
  [k: string]: unknown
}
/** Quote `amount` (human units) of `from` into `to`. */
export async function quoteSwap(from: string, to: string, amount: string): Promise<SwapQuote> {
  const a = LIVE_ASSETS[from], b = LIVE_ASSETS[to]
  if (!a || !b || from === to) throw new Error('Pick two different assets.')
  const raw = parseAmount(amount, a.decimals)
  if (raw <= 0n) throw new Error('Enter an amount above zero.')
  const url = `${JUP}/quote?inputMint=${jupMint(a.mint)}&outputMint=${jupMint(b.mint)}&amount=${raw}&slippageBps=${SWAP_SLIPPAGE_BPS}`
  const res = await fetch(url)
  const q = await res.json()
  if (!res.ok || q.error) throw new Error(`No swap route right now (${q.error ?? res.status}). Try a different amount.`)
  return q as SwapQuote
}
export type SwapStep = 'withdraw' | 'swap' | 'deposit' | 'done'
export type SwapResult = { withdrawSig: string; swapSig: string; depositSig: string; received: string; asset: string }

export type LiveBalance = { asset: string; amount: number; utxos: number }
export type LiveTx = { id: string; detail: string }

const TREASURY_ADDR = address(TREASURY)
/** pullhaus app fee for an amount in base units (rounded down). */
export const feeFor = (amount: bigint) => (amount * FEE_BPS) / 10_000n

export class RingsSession {
  private constructor(
    readonly client: SprClient,
    readonly wallet: StdWallet,
    readonly account: WalletAccount,
    readonly owner: Address,
    readonly keys: LocalKeys,
    readonly shielded: ShieldedWallet,
    /** Private fee payments need the treasury registered on Privacy Rings. */
    readonly treasuryRegistered: boolean,
  ) {}

  /** True when private transfers carry the app fee. */
  get feesActive() {
    return this.treasuryRegistered && this.owner !== TREASURY_ADDR
  }

  /** Lists installed wallets that can sign messages and transactions. */
  static wallets(): StdWallet[] {
    return getWallets().get().filter((w) => 'solana:signMessage' in w.features && 'solana:signTransaction' in w.features)
  }

  /** Wallet extensions often register after the page loads; call `cb` whenever one does. */
  static onWalletsChange(cb: () => void): () => void {
    const api = getWallets()
    const offA = api.on('register', cb)
    const offB = api.on('unregister', cb)
    return () => { offA(); offB() }
  }

  static async connect(wallet: StdWallet, onStatus: (s: string) => void = () => {}): Promise<RingsSession> {
    if (!API_KEY) throw new Error('Set VITE_HELIUS_API_KEY in web/.env.local to use Privacy Rings.')
    onStatus('Connecting wallet')
    const connectFeature = wallet.features['standard:connect'] as { connect(): Promise<{ accounts: readonly WalletAccount[] }> }
    const { accounts } = await connectFeature.connect()
    const account = accounts[0]
    if (!account) throw new Error('Wallet returned no account.')
    const owner = address(account.address)

    onStatus('Starting Privacy Rings client')
    // proverTee: the SDK only sends proof inputs to a prover enclave that attests to
    // Helius' signed policy for this network (AWS Nitro). Required for every remote prover.
    const client = await createSprClient({
      solanaRpcUrl: `https://${CLUSTER}.helius-rpc.com/?api-key=${API_KEY}`,
      proverTee: SignedTeePolicy.forNetwork(CLUSTER),
    })

    onStatus('Sign once to unlock your private balance')
    const message = new TextEncoder().encode(signInMessage(owner))
    const signFeature = wallet.features['solana:signMessage'] as {
      signMessage(...i: { account: WalletAccount; message: Uint8Array }[]): Promise<readonly { signature: Uint8Array }[]>
    }
    const [{ signature }] = await signFeature.signMessage({ account, message })
    const walletPub = new Uint8Array(account.publicKey)
    if (!(await verifyEd25519(walletPub, message, signature))) {
      throw new Error('Your wallet returned a signature that does not match the sign-in message. Please try again.')
    }
    const keys = await keysFromSignature(walletPub, new Uint8Array(signature), client.proofService)
    const shielded = new ShieldedWallet({ identity: keys.address() })
    const treasuryRegistered = await isWalletRegistered({ rpc: client, owner: TREASURY_ADDR }).catch(() => false)
    const session = new RingsSession(client, wallet, account, owner, keys, shielded, treasuryRegistered)

    onStatus('Checking registration')
    // Don't swallow lookup errors: guessing "not registered" on a network blip would try to re-register.
    const existing = await resolveRegisteredAddress({ rpc: client, owner }).catch((e) => {
      throw Object.assign(new Error("Couldn't reach Helius to check your registration. Please try again in a moment."), { cause: e })
    })
    if (!existing) {
      // Registration creates a 100-byte record (one-time rent) and the wallet must stay rent-exempt.
      await ensureSol(client, owner, 'registration', (await rentFor(client, REGISTRY_RECORD_BYTES)) + TX_FEE_MARGIN)
      onStatus('Approve one-time registration of your shielded address')
      const tx = await buildRegistrationTransaction({ client, owner, address: keys.address() }).catch((e) => {
        const codes = JSON.stringify(e, Object.getOwnPropertyNames(e ?? {})) + String(e?.cause?.code ?? '')
        if (/USER_RECORD_KEYS_MISMATCH/.test(codes)) {
          throw new Error('This wallet is already registered on Privacy Rings with different keys (for example by another app). pullhaus will not overwrite it.')
        }
        throw e
      })
      if (tx) await session.send(tx, false)
    } else if (!sameBytes(existing.address.toBytes(), keys.address().toBytes())) {
      // Never overwrite a registration: that could hide an existing private balance.
      throw new Error('This wallet is already registered on Privacy Rings with different keys (for example by another app). pullhaus will not overwrite it.')
    }
    onStatus('Syncing private balance')
    await session.sync()
    return session
  }

  /** Wallet signs, we submit, then wait for the indexer to see it. */
  async send(tx: Transaction, privateTx: boolean): Promise<string> {
    const sign = this.wallet.features['solana:signTransaction'] as {
      signTransaction(...i: { account: WalletAccount; transaction: Uint8Array; chain?: string }[]): Promise<readonly { signedTransaction: Uint8Array }[]>
    }
    // kit types this as ReadonlyUint8Array; wallets want a plain copy
    const bytes = new Uint8Array(getTransactionEncoder().encode(tx) as unknown as Uint8Array)
    const [{ signedTransaction }] = await sign.signTransaction({ account: this.account, transaction: bytes, chain: CHAIN })
    const signed = getTransactionDecoder().decode(signedTransaction)
    const sig = await this.client.solanaRpc.sendTransaction(getBase64EncodedWireTransaction(signed), { encoding: 'base64' }).send()
    if (privateTx) await this.client.confirmPrivateTransaction(sig)
    else await this.client.confirmTransaction(sig)
    return sig
  }

  async sync() {
    await syncWallet({ wallet: this.shielded, keys: this.keys, client: this.client })
  }

  balances(): LiveBalance[] {
    return getPrivateTokenBalances(this.shielded).map((b) => {
      const sym = symbolFor(b.mint)
      const dec = LIVE_ASSETS[sym]?.decimals ?? 0
      return { asset: sym, amount: Number(formatAmount(b.amount, dec)), utxos: b.utxos.length }
    })
  }

  history(): LiveTx[] {
    return getPrivateTransactions(this.shielded).map((t, i) => ({ id: String(i), detail: JSON.stringify(t, (_k, v) => (typeof v === 'bigint' ? v.toString() : v)).slice(0, 140) }))
  }

  private asset(sym: string) {
    const a = LIVE_ASSETS[sym]
    if (!a) throw new Error(`${sym} isn't enabled on Privacy Rings in pullhaus yet. Use SOL or USDC.`)
    return a
  }

  private base() {
    return { client: this.client, wallet: this.shielded, keys: this.keys, feePayer: this.owner }
  }

  /**
   * Public balance → private balance. `recipient` defaults to yourself; any registered Solana
   * address works (payment links). With `chargeFee`, the payer also sends the 0.25% app fee to
   * the treasury in the same transaction. Deposits are public anyway, so this leaks nothing new.
   */
  async deposit(sym: string, amount: string, recipient?: string, chargeFee = false): Promise<string> {
    const a = this.asset(sym)
    const value = parseAmount(amount, a.decimals)
    const fee = chargeFee && this.owner !== TREASURY_ADDR ? feeFor(value) : 0n
    await ensureSol(this.client, this.owner, 'this deposit', (a.mint === SOL_MINT ? value + fee : 0n) + TX_FEE_MARGIN)
    const tx = await buildDepositTransaction({
      client: this.client, feePayer: this.owner, asset: a.mint, amount: value,
      recipient: recipient ? address(recipient) : this.keys.address(),
      setupInstructions: fee > 0n ? await this.feeInstructions(sym, fee) : undefined,
    })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /**
   * Private → private. Amount and asset are hidden; addresses are visible on the default ring.
   * The recipient gets the full amount; the 0.25% app fee is a second private output to the treasury.
   */
  async transfer(sym: string, amount: string, to: string): Promise<string> {
    const a = this.asset(sym)
    const value = parseAmount(amount, a.decimals)
    const fee = this.feesActive ? feeFor(value) : 0n
    const tx = fee > 0n
      ? await buildMultiTransferTransaction({
          ...this.base(), asset: a.mint,
          payments: [{ recipient: address(to), amount: value }, { recipient: TREASURY_ADDR, amount: fee }],
        })
      : await buildTransferTransaction({ ...this.base(), recipient: address(to), asset: a.mint, amount: value })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Most payroll recipients per transaction (Rings allows 15 outputs; one is the fee). */
  get maxRecipients() {
    return this.feesActive ? 14 : 15
  }

  /** One private transaction paying many recipients (payroll), plus the app fee on the total. */
  async multiTransfer(sym: string, payments: { to: string; amount: string }[]): Promise<string> {
    const a = this.asset(sym)
    if (payments.length > this.maxRecipients) throw new Error(`Up to ${this.maxRecipients} recipients per transaction.`)
    const outs = payments.map((p) => ({ recipient: address(p.to), amount: parseAmount(p.amount, a.decimals) }))
    const fee = this.feesActive ? feeFor(outs.reduce((s, o) => s + o.amount, 0n)) : 0n
    const tx = await buildMultiTransferTransaction({
      ...this.base(), asset: a.mint,
      payments: fee > 0n ? [...outs, { recipient: TREASURY_ADDR, amount: fee }] : outs,
    })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Private balance → public Solana address. */
  async withdraw(sym: string, amount: string, to: string): Promise<string> {
    const a = this.asset(sym)
    const tx = await buildWithdrawalTransaction({ ...this.base(), recipient: address(to), asset: a.mint, amount: parseAmount(amount, a.decimals) })
    const sig = await this.send(tx, true)
    await this.sync()
    return sig
  }

  /** Wallet signs a ready-made (v0) transaction, e.g. from Jupiter; we submit and confirm. */
  private async sendRaw(bytes: Uint8Array): Promise<string> {
    const sign = this.wallet.features['solana:signTransaction'] as {
      signTransaction(...i: { account: WalletAccount; transaction: Uint8Array; chain?: string }[]): Promise<readonly { signedTransaction: Uint8Array }[]>
    }
    const [{ signedTransaction }] = await sign.signTransaction({ account: this.account, transaction: bytes, chain: CHAIN })
    const b64 = btoa(String.fromCharCode(...new Uint8Array(signedTransaction)))
    const sig = await this.client.solanaRpc.sendTransaction(b64 as never, { encoding: 'base64', skipPreflight: false }).send()
    await this.client.confirmTransaction(sig)
    return sig
  }

  /** Public balance of `sym` in the connected wallet, in base units. */
  private async publicRaw(sym: string): Promise<bigint> {
    const a = this.asset(sym)
    if (a.mint === SOL_MINT) return (await this.client.solanaRpc.getBalance(this.owner).send()).value
    const [ata] = await findAssociatedTokenPda({ owner: this.owner, mint: a.mint, tokenProgram: TOKEN_PROGRAM_ADDRESS })
    try {
      const r = await this.client.solanaRpc.getTokenAccountBalance(ata).send()
      return BigInt(r.value.amount)
    } catch {
      return 0n // no token account yet
    }
  }

  /**
   * Private swap: withdraw `amount` of `from` → swap on Jupiter → deposit the result back
   * into the private balance (0.25% app fee on the output). The withdraw, swap and deposit
   * are public on-chain; the balance before and after stays private. If a later step
   * fails, the funds are in the user's own wallet and the error says so.
   */
  async swap(from: string, to: string, amount: string, onStep: (s: SwapStep) => void): Promise<SwapResult> {
    this.asset(from); const b = this.asset(to)
    if (from === to) throw new Error('Pick two different assets.')
    // Fees for three transactions, plus wrapping/token-account headroom.
    await ensureSol(this.client, this.owner, 'this swap (three transactions)', TX_FEE_MARGIN * 3n + 3_000_000n)
    await quoteSwap(from, to, amount) // fail fast if there's no route

    onStep('withdraw')
    const withdrawSig = await this.withdraw(from, amount, this.owner)

    let swapSig = ''
    try {
      onStep('swap')
      const before = await this.publicRaw(to)
      const quote = await quoteSwap(from, to, amount) // fresh quote right before signing
      const res = await fetch(`${JUP}/swap`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ quoteResponse: quote, userPublicKey: this.owner, wrapAndUnwrapSol: true, dynamicComputeUnitLimit: true, prioritizationFeeLamports: 'auto' }),
      })
      const j = await res.json()
      if (!res.ok || !j.swapTransaction) throw new Error(`Jupiter couldn't build the swap (${j.error ?? res.status}).`)
      swapSig = await this.sendRaw(Uint8Array.from(atob(j.swapTransaction), (c) => c.charCodeAt(0)))
      const after = await this.publicRaw(to)
      let got = after - before
      // SOL output: the swap's own network fee came out of the same balance; keep room for the deposit's fee.
      if (b.mint === SOL_MINT) got -= TX_FEE_MARGIN
      if (got <= 0n) throw new Error('The swap went through but nothing arrived to deposit.')

      onStep('deposit')
      const received = formatAmount(got, b.decimals)
      const depositSig = await this.deposit(to, received, undefined, true)
      onStep('done')
      return { withdrawSig, swapSig, depositSig, received, asset: to }
    } catch (e) {
      const where = swapSig
        ? `The swap went through, but depositing the ${to} back failed. Your ${to} is in your wallet. Use Vault → Shield to make it private again.`
        : `Your ${amount} ${from} was withdrawn to your wallet, but the swap didn't go through. It's safe in your wallet. Use Vault → Shield to make it private again.`
      throw Object.assign(new Error(where), { cause: e, recovery: true })
    }
  }

  /** Public fee transfer to the treasury (SOL, or SPL to the treasury's token account). */
  private async feeInstructions(sym: string, fee: bigint): Promise<Instruction[]> {
    const a = this.asset(sym)
    const payer = createNoopSigner(this.owner)
    if (a.mint === SOL_MINT) {
      // A transfer can't leave an account below the rent-exempt minimum. If the treasury is
      // ever that low, skip the fee rather than fail the customer's payment.
      const [{ value: bal }, rentMin] = await Promise.all([
        this.client.solanaRpc.getBalance(TREASURY_ADDR).send(),
        this.client.solanaRpc.getMinimumBalanceForRentExemption(0n).send(),
      ])
      if (bal + fee < rentMin) return []
      return [getTransferSolInstruction({ source: payer, destination: TREASURY_ADDR, amount: fee })]
    }
    const [source] = await findAssociatedTokenPda({ owner: this.owner, mint: a.mint, tokenProgram: TOKEN_PROGRAM_ADDRESS })
    const [destination] = await findAssociatedTokenPda({ owner: TREASURY_ADDR, mint: a.mint, tokenProgram: TOKEN_PROGRAM_ADDRESS })
    return [
      await getCreateAssociatedTokenIdempotentInstructionAsync({ payer, owner: TREASURY_ADDR, mint: a.mint }),
      getTransferCheckedInstruction({ source, mint: a.mint, destination, authority: payer, amount: fee, decimals: a.decimals }),
    ]
  }

  async disconnect() {
    const f = this.wallet.features['standard:disconnect'] as { disconnect(): Promise<void> } | undefined
    await f?.disconnect().catch(() => {})
  }
}
